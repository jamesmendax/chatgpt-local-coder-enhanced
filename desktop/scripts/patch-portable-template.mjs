import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

// electron-builder does not expose the portable NSIS template as a target
// option. Patch the installed template at build time so the generated
// launcher extracts to a short, process-isolated directory. This keeps the
// complete MCP dependency tree below the legacy Windows MAX_PATH boundary
// even when %TEMP% itself is nested deeply.
const here = path.dirname(fileURLToPath(import.meta.url));
const template = path.resolve(here, "..", "node_modules", "app-builder-lib", "templates", "nsis", "portable.nsi");
const source = fs.readFileSync(template, "utf8");
const newline = source.includes("\r\n") ? "\r\n" : "\n";
const oldBlock = [
  "  StrCpy $INSTDIR \"$PLUGINSDIR\\app\"",
  "  !ifdef UNPACK_DIR_NAME",
  "    StrCpy $INSTDIR \"$TEMP\\${UNPACK_DIR_NAME}\"",
  "  !endif",
].join(newline);
const newBlock = [
  "  ; Keep the extraction root short while retaining per-process isolation.",
  "  ; Long dependency paths otherwise exceed MAX_PATH under a nested %TEMP%.",
  "  Push $R0",
  "  Push $R1",
  "  System::Call 'Kernel32::GetCurrentProcessId() i.R0'",
  "  StrCpy $R1 \"$TEMP\\cgh-$R0\"",
  "  StrCpy $INSTDIR $R1",
  "  Pop $R1",
  "  Pop $R0",
].join(newline);

if (source.includes("GetCurrentProcessId()")) {
  // Keep the patch idempotent while correcting templates generated by an
  // earlier build of this release candidate.
  const corrected = source.replace("System::Call 'Kernel32::GetCurrentProcessId() i .R0'", "System::Call 'Kernel32::GetCurrentProcessId() i.R0'");
  if (corrected !== source) fs.writeFileSync(template, corrected, "utf8");
  console.log(`[portable-template] already patched: ${template}`);
} else {
  if (!source.includes(oldBlock)) {
    throw new Error(`electron-builder portable template did not match expected block: ${template}`);
  }
  fs.writeFileSync(template, source.replace(oldBlock, newBlock), "utf8");
  console.log(`[portable-template] patched short per-process extraction root: ${template}`);
}
